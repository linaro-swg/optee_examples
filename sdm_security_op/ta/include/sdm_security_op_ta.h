#ifndef TA_SDM_SECURITY_OP_H
#define TA_SDM_SECURITY_OP_H

#include <stdint.h>

#define TA_SDM_SECURITY_OP_UUID \
	{ 0x5ec00b17, 0x7b2a, 0x4e5d, \
		{ 0x9c, 0x1a, 0x10, 0x0c, 0x01, 0x2e, 0xc0, 0x1d } }

#define TA_SDM_SECURITY_OP_CMD_APPLY	0

#ifndef __PTA_SDM_SVC_H
#define SDM_SECOPT_FIRMWARE_JOINT_SIGNING	(1U << 0)
#define SDM_SECOPT_AES_KEY_UPDATE_MODE		(1U << 1)
#define SDM_SECOPT_JTAG_DISABLE			(1U << 2)
#define SDM_SECOPT_HPS_DEBUG_DISABLE		(1U << 3)
#define SDM_SECOPT_VIRTUAL_EFUSE_DISABLE	(1U << 4)
#define SDM_SECOPT_HPS_ZEROIZATION		(1U << 5)
#define SDM_SECOPT_FPGA_ZEROIZATION		(1U << 6)
#define SDM_SECOPT_PUF_AES_KEY_DISABLE		(1U << 7)
#define SDM_SECOPT_BBRAM_AES_KEY_DISABLE	(1U << 8)
#define SDM_SECOPT_EFUSE_AES_KEY_DISABLE	(1U << 9)
#define SDM_SECOPT_PUF_ENROLLMENT_DISABLE	(1U << 10)
#define SDM_SECOPT_SECURE_CLOCK_ONLY		(1U << 11)
#define SDM_SECOPT_CRC_ENABLE			(1U << 12)
#define SDM_SECOPT_ALIASL1_DISABLE		(1U << 16)
#define SDM_SECOPT_DISABLE_BETA_MODE		(1U << 17)
#define SDM_SECOPT_TEST_MODE			(1U << 31)

#define SDM_SECOPT_VALID_MASK ( \
	SDM_SECOPT_FIRMWARE_JOINT_SIGNING | \
	SDM_SECOPT_AES_KEY_UPDATE_MODE    | \
	SDM_SECOPT_JTAG_DISABLE           | \
	SDM_SECOPT_HPS_DEBUG_DISABLE      | \
	SDM_SECOPT_VIRTUAL_EFUSE_DISABLE  | \
	SDM_SECOPT_HPS_ZEROIZATION        | \
	SDM_SECOPT_FPGA_ZEROIZATION       | \
	SDM_SECOPT_PUF_AES_KEY_DISABLE    | \
	SDM_SECOPT_BBRAM_AES_KEY_DISABLE  | \
	SDM_SECOPT_EFUSE_AES_KEY_DISABLE  | \
	SDM_SECOPT_PUF_ENROLLMENT_DISABLE | \
	SDM_SECOPT_SECURE_CLOCK_ONLY      | \
	SDM_SECOPT_CRC_ENABLE             | \
	SDM_SECOPT_ALIASL1_DISABLE        | \
	SDM_SECOPT_DISABLE_BETA_MODE      | \
	SDM_SECOPT_TEST_MODE)

#define SDM_SECOPT_HOST_FLAG_NON_VOLATILE	(1U << 0)
#define SDM_SECOPT_HOST_FLAGS_VALID_MASK	SDM_SECOPT_HOST_FLAG_NON_VOLATILE
#endif

#define SDM_SECOPT_FUNCTIONAL_MASK \
	(SDM_SECOPT_VALID_MASK & ~SDM_SECOPT_TEST_MODE)

#endif /* TA_SDM_SECURITY_OP_H */
